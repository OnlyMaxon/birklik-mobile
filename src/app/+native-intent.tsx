/**
 * Перевод адреса сайта в маршрут приложения.
 *
 * Сюда expo-router отдаёт КАЖДУЮ ссылку, по которой приложение открыли, — и при
 * запуске, и когда оно уже работало. Файл обязан быть именно `+native-intent` и
 * лежать в корне `app/`: роутер ищет его по имени.
 *
 * ⚠️ Нужен потому, что адреса сайта и маршруты приложения РАЗНЫЕ. На сайте у
 * азербайджанской версии префикса нет, а у русской и английской он есть:
 *
 * ```
 * birklik.az/property/abc123      → /property/abc123   совпало само
 * birklik.az/ru/property/abc123   → /property/abc123   нужен перевод
 * birklik.az/ru/kiraye/baku       → /                   такого экрана нет
 * ```
 *
 * Без перевода русская ссылка открывала бы пустой экран «маршрут не найден» —
 * а делятся как раз русскими ссылками.
 *
 * ⚠️ Приходит ПОЛНЫЙ адрес со схемой, а не путь (`https://birklik.az/...`), и
 * схема бывает не только `https`: своя `birklik://`, адрес запуска с рабочего
 * стола, ссылки из уведомлений. Всё чужое пропускаем БЕЗ ИЗМЕНЕНИЙ — иначе
 * обычный запуск приложения превратился бы в разбор ссылки.
 */
export function redirectSystemPath({path}: {path: string; initial: boolean}): string {
  try {
    const url = new URL(path)

    // Не наша ссылка — не наше дело.
    if (url.protocol !== 'https:' && url.protocol !== 'http:') return path
    if (url.hostname !== 'birklik.az' && url.hostname !== 'www.birklik.az') return path

    // Язык из адреса убираем: экран сам показывает тот, что выбран в приложении.
    const withoutLocale = url.pathname.replace(/^\/(az|ru|en)(?=\/|$)/, '')

    const property = withoutLocale.match(/^\/property\/([^/]+)/)
    if (property) return `/property/${property[1]}`

    // Остальное приложение не умеет — и это не ошибка: в манифесте мы просим
    // только ссылки на объявления. Домой лучше, чем «маршрут не найден».
    return '/'
  } catch {
    // Строка не разобралась как адрес. Трогать её тем более нельзя.
    return path
  }
}
