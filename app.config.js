/**
 * Надстройка над `app.json` — только то, что нельзя записать статично.
 *
 * ⚠️ **`app.json` НИКУДА НЕ ДЕЛСЯ и остаётся источником правды.** Expo отдаёт
 * его содержимое сюда параметром `config`, а мы дописываем сверху одно поле.
 * Переносить всю настройку в код было бы хуже: статичное удобнее читать и
 * труднее сломать, а разница между двумя файлами сразу видна в истории.
 *
 * ⚠️ **Зачем это вообще понадобилось.** `GoogleService-Info.plist` в гите нет и
 * быть не должно, а EAS собирает ТОЛЬКО закоммиченное. Статичный `app.json`
 * переменные окружения читать не умеет, поэтому путь к файлу было некуда
 * положить: указать `./GoogleService-Info.plist` значило бы, что облачная
 * сборка не найдёт его и соберёт приложение БЕЗ Firebase — экраны есть, данных
 * нет, и ошибки никакой.
 *
 * ⚠️ Android здесь намеренно НЕ трогается. Его `googleServicesFile` остаётся в
 * `app.json`, потому что `android/` у нас собирается локально и `expo prebuild`
 * для него запрещён — поле просто не участвует. Симметрия ради симметрии стоила
 * бы правки в единственной части проекта, которую трогать нельзя.
 */

/**
 * Путь к `GoogleService-Info.plist`.
 *
 * Локально — файл в корне, рядом с `google-services.json` для Android. В EAS —
 * переменная окружения типа «файл»: облако кладёт её содержимое во временный
 * файл и подставляет сюда его путь.
 *
 * ```bash
 * eas env:create --name GOOGLE_SERVICES_INFO_PLIST --type file \
 *   --scope project --value ./GoogleService-Info.plist
 * ```
 */
const IOS_FIREBASE_CONFIG =
  process.env.GOOGLE_SERVICES_INFO_PLIST || './GoogleService-Info.plist'

module.exports = ({config}) => ({
  ...config,
  ios: {
    ...config.ios,
    googleServicesFile: IOS_FIREBASE_CONFIG
  }
})
